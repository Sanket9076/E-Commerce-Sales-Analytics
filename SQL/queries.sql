-- 98. Stored Procedure: Get monthly sales performance report for a specific state
DELIMITER //

CREATE PROCEDURE sp_monthly_sales_by_state(IN input_state VARCHAR(5))
BEGIN
    SELECT 
        DATE_FORMAT(o.order_purchase_timestamp, '%Y-%m') AS sale_month,
        COUNT(DISTINCT o.order_id) AS orders_count,
        SUM(oi.price * oi.quantity) AS total_revenue,
        SUM(oi.freight_value) AS total_freight
    FROM orders o
    INNER JOIN customers c ON o.customer_id = c.customer_id
    INNER JOIN order_items oi ON o.order_id = oi.order_id
    WHERE c.customer_state = input_state
    GROUP BY DATE_FORMAT(o.order_purchase_timestamp, '%Y-%m')
    ORDER BY sale_month ASC;
END //

DELIMITER ;

