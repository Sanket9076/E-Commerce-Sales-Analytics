-- SECTION 3: Relational Joins (Queries 31-45)
-- ====================================================================

-- 31. Join orders and customers to see which customer (unique ID) placed which order
SELECT o.order_id, c.customer_unique_id, o.order_purchase_timestamp 
FROM orders o
INNER JOIN customers c ON o.customer_id = c.customer_id;

-- 32. Retrieve order items details along with English category name
SELECT oi.order_item_id, oi.order_id, p.product_id, cat.product_category_name_english, oi.price 
FROM order_items oi
INNER JOIN products p ON oi.product_id = p.product_id
INNER JOIN categories cat ON p.product_category_name = cat.product_category_name;

-- 33. Left Join to list all customers and their order status (including those who haven't ordered, if any)
SELECT c.customer_unique_id, o.order_id, o.order_status 
FROM customers c
LEFT JOIN orders o ON c.customer_id = o.customer_id;

-- 34. Calculate total revenue generated by each seller
SELECT s.seller_id, s.seller_state, SUM(oi.price * oi.quantity) AS total_revenue 
FROM order_items oi
INNER JOIN sellers s ON oi.seller_id = s.seller_id
GROUP BY s.seller_id, s.seller_state
ORDER BY total_revenue DESC;

-- 35. Find average delivery time (days) for each shipping carrier
SELECT sh.shipping_carrier, AVG(DATEDIFF(sh.shipping_actual_delivery_date, o.order_purchase_timestamp)) AS avg_delivery_days 
FROM shipping sh
INNER JOIN orders o ON sh.order_id = o.order_id
WHERE sh.shipping_status = 'delivered'
GROUP BY sh.shipping_carrier;

-- 36. Find average review score for each product category (English name)
SELECT cat.product_category_name_english, AVG(r.review_score) AS avg_score, COUNT(r.review_id) AS total_reviews
FROM reviews r
INNER JOIN orders o ON r.order_id = o.order_id
INNER JOIN order_items oi ON o.order_id = oi.order_id
INNER JOIN products p ON oi.product_id = p.product_id
INNER JOIN categories cat ON p.product_category_name = cat.product_category_name
GROUP BY cat.product_category_name_english
ORDER BY avg_score DESC;

-- 37. List products that have never been ordered (if any)
SELECT p.product_id, p.product_category_name, p.product_base_price 
FROM products p
LEFT JOIN order_items oi ON p.product_id = oi.product_id
WHERE oi.product_id IS NULL;

-- 38. Self Join: Find pairs of customers living in the same city and state (limited to 20 pairs)
SELECT c1.customer_unique_id AS customer_1, c2.customer_unique_id AS customer_2, c1.customer_city, c1.customer_state
FROM customers c1
INNER JOIN customers c2 ON c1.customer_city = c2.customer_city 
    AND c1.customer_state = c2.customer_state 
    AND c1.customer_unique_id < c2.customer_unique_id
LIMIT 20;

-- 39. Combine reviews and returns to see if returned products had poor review scores
SELECT r.return_id, r.order_id, r.product_id, rev.review_score, r.return_reason 
FROM returns r
INNER JOIN reviews rev ON r.order_id = rev.order_id;

-- 40. Get breakdown of payment methods and their total contribution to revenue
SELECT p.payment_type, SUM(p.payment_value) AS total_payment_value, COUNT(DISTINCT p.order_id) AS total_orders
FROM payments p
GROUP BY p.payment_type
ORDER BY total_payment_value DESC;

-- 41. Find top 5 cities with highest sales revenue
SELECT c.customer_city, SUM(oi.price * oi.quantity) AS city_revenue 
FROM order_items oi
INNER JOIN orders o ON oi.order_id = o.order_id
INNER JOIN customers c ON o.customer_id = c.customer_id
GROUP BY c.customer_city
ORDER BY city_revenue DESC
LIMIT 5;

-- 42. Get number of delayed deliveries grouped by state
SELECT c.customer_state, COUNT(o.order_id) AS delayed_orders_count 
FROM orders o
INNER JOIN customers c ON o.customer_id = c.customer_id
WHERE o.order_status = 'delivered' AND o.order_delivered_customer_date > o.order_estimated_delivery_date
GROUP BY c.customer_state
ORDER BY delayed_orders_count DESC;

-- 43. Multi-table join to retrieve full customer order history profile
SELECT 
    o.order_id, c.customer_unique_id, o.order_status, 
    SUM(oi.price * oi.quantity) AS items_cost, 
    SUM(oi.freight_value) AS freight_cost,
    SUM(p.payment_value) AS amount_paid
FROM orders o
INNER JOIN customers c ON o.customer_id = c.customer_id
INNER JOIN order_items oi ON o.order_id = oi.order_id
INNER JOIN payments p ON o.order_id = p.order_id
GROUP BY o.order_id, c.customer_unique_id, o.order_status
LIMIT 10;

-- 44. Find the average return rate of items sold by seller state
SELECT s.seller_state, COUNT(r.return_id) AS returns_count, COUNT(oi.order_item_id) AS items_sold, (COUNT(r.return_id) / COUNT(oi.order_item_id)) * 100 AS return_rate
FROM order_items oi
INNER JOIN sellers s ON oi.seller_id = s.seller_id
LEFT JOIN returns r ON oi.order_id = r.order_id AND oi.product_id = r.product_id
GROUP BY s.seller_state
ORDER BY return_rate DESC;

-- 45. Join orders with payments and check if any payment value is less than total order value (discrepancy check)
SELECT o.order_id, SUM(oi.price * oi.quantity + oi.freight_value) AS order_total, SUM(p.payment_value) AS payments_total
FROM orders o
INNER JOIN order_items oi ON o.order_id = oi.order_id
INNER JOIN payments p ON o.order_id = p.order_id
GROUP BY o.order_id
HAVING payments_total < order_total - 0.05
LIMIT 10;


