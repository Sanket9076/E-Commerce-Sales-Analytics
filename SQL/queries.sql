)
SELECT 
    order_date,
    daily_revenue,
    AVG(daily_revenue) OVER (ORDER BY order_date ROWS BETWEEN 29 PRECEDING AND CURRENT ROW) AS 30_day_moving_revenue_avg
FROM DailySalesRevenue
