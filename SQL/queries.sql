-- 46. Find products with price above the overall average product price
SELECT product_id, product_category_name, product_base_price 
FROM products 
WHERE product_base_price > (SELECT AVG(product_base_price) FROM products);

-- 47. Retrieve orders placed by customers from São Paulo using subquery
SELECT order_id, customer_id, order_status 
FROM orders 
WHERE customer_id IN (SELECT customer_id FROM customers WHERE customer_state = 'SP');

-- 48. Correlated Subquery: Find products that are the most expensive in their category
SELECT p1.product_id, p1.product_category_name, p1.product_base_price 
FROM products p1
WHERE p1.product_base_price = (
    SELECT MAX(p2.product_base_price) 
    FROM products p2 
    WHERE p2.product_category_name = p1.product_category_name
);

-- 49. CTE to calculate monthly revenue trends
WITH MonthlySales AS (
    SELECT 
        DATE_FORMAT(order_purchase_timestamp, '%Y-%m') AS sale_month,
        SUM(price * quantity) AS monthly_revenue
    FROM orders o
    INNER JOIN order_items oi ON o.order_id = oi.order_id
    GROUP BY DATE_FORMAT(order_purchase_timestamp, '%Y-%m')
)
SELECT sale_month, monthly_revenue 
FROM MonthlySales 
ORDER BY sale_month ASC;

-- 50. CTE to identify the top 5 spending customers
WITH CustomerSpend AS (
    SELECT c.customer_unique_id, SUM(oi.price * oi.quantity) AS total_spend
    FROM orders o
    INNER JOIN customers c ON o.customer_id = c.customer_id
    INNER JOIN order_items oi ON o.order_id = oi.order_id
    GROUP BY c.customer_unique_id
)
SELECT customer_unique_id, total_spend 
FROM CustomerSpend 
ORDER BY total_spend DESC 
LIMIT 5;

-- 51. Subquery in SELECT: List products and their difference from the category average price
SELECT 
    product_id, 
    product_category_name, 
    product_base_price,
    product_base_price - (
        SELECT AVG(p2.product_base_price) 
        FROM products p2 
        WHERE p2.product_category_name = p1.product_category_name
    ) AS price_diff_from_avg
FROM products p1
LIMIT 10;

-- 52. Subquery with EXISTS: Retrieve sellers who have had at least one order canceled
SELECT s.seller_id, s.seller_city, s.seller_state 
FROM sellers s
WHERE EXISTS (
    SELECT 1 
    FROM order_items oi
    INNER JOIN orders o ON oi.order_id = o.order_id
    WHERE oi.seller_id = s.seller_id AND o.order_status = 'canceled'
);

-- 53. CTE to compute repeat purchase status of users
WITH UserPurchaseCounts AS (
    SELECT c.customer_unique_id, COUNT(o.order_id) AS order_count
    FROM orders o
    INNER JOIN customers c ON o.customer_id = c.customer_id
    GROUP BY c.customer_unique_id
)
SELECT 
    order_count AS orders_placed, 
    COUNT(customer_unique_id) AS customer_count,
    (COUNT(customer_unique_id) * 100.0 / (SELECT COUNT(*) FROM (SELECT DISTINCT customer_unique_id FROM customers) AS total)) AS customer_pct
FROM UserPurchaseCounts
GROUP BY order_count
ORDER BY order_count ASC;

-- 54. CTE to calculate average review score by seller
WITH SellerReviews AS (
    SELECT oi.seller_id, r.review_score
    FROM order_items oi
    INNER JOIN reviews r ON oi.order_id = r.order_id
)
SELECT seller_id, AVG(review_score) AS avg_seller_rating, COUNT(review_score) AS total_ratings
FROM SellerReviews
GROUP BY seller_id
HAVING total_ratings >= 5
ORDER BY avg_seller_rating DESC
LIMIT 10;

-- 55. Subquery to find orders where delivery took longer than the estimated time
SELECT order_id, customer_id, DATEDIFF(order_delivered_customer_date, order_purchase_timestamp) AS actual_delivery_days, DATEDIFF(order_estimated_delivery_date, order_purchase_timestamp) AS estimated_delivery_days
FROM orders 
WHERE order_status = 'delivered' 
  AND DATEDIFF(order_delivered_customer_date, order_purchase_timestamp) > DATEDIFF(order_estimated_delivery_date, order_purchase_timestamp);

-- 56. CTE to calculate regional shipping delay percentages
WITH RegionalShipping AS (
    SELECT c.customer_state, 
           CASE WHEN o.order_delivered_customer_date > o.order_estimated_delivery_date THEN 1 ELSE 0 END AS is_delayed
    FROM orders o
    INNER JOIN customers c ON o.customer_id = c.customer_id
    WHERE o.order_status = 'delivered'
)
SELECT customer_state, COUNT(*) AS total_delivered, SUM(is_delayed) AS total_delayed, (SUM(is_delayed) * 100.0 / COUNT(*)) AS delay_pct
FROM RegionalShipping
GROUP BY customer_state
ORDER BY delay_pct DESC;

-- 57. Nested subquery to find categories that contain products with returns
SELECT product_category_name_english 
FROM categories 
WHERE product_category_name IN (
    SELECT DISTINCT product_category_name 
    FROM products 
    WHERE product_id IN (
        SELECT DISTINCT product_id FROM returns WHERE return_status = 'approved'
    )
);

-- 58. CTE to calculate the revenue concentration by category
WITH CategoryRevenue AS (
    SELECT p.product_category_name, SUM(oi.price * oi.quantity) AS revenue
    FROM order_items oi
    INNER JOIN products p ON oi.product_id = p.product_id
    GROUP BY p.product_category_name
)
SELECT product_category_name, revenue, (revenue * 100.0 / (SELECT SUM(price * quantity) FROM order_items)) AS revenue_share_pct
FROM CategoryRevenue
ORDER BY revenue DESC;

-- 59. CTE to analyze seasonal sales variation (Quarterly sales value)
WITH QuarterlySales AS (
    SELECT 
        YEAR(order_purchase_timestamp) AS yr,
        QUARTER(order_purchase_timestamp) AS qtr,
        SUM(price * quantity) AS total_sales
    FROM orders o
    INNER JOIN order_items oi ON o.order_id = oi.order_id
    GROUP BY YEAR(order_purchase_timestamp), QUARTER(order_purchase_timestamp)
)
SELECT yr, qtr, total_sales 
FROM QuarterlySales 
ORDER BY yr ASC, qtr ASC;

-- 60. Subquery to identify users whose first order was in 2024 and who also ordered in 2026
SELECT DISTINCT customer_unique_id 
FROM customers c
INNER JOIN orders o ON c.customer_id = o.customer_id
WHERE YEAR(o.order_purchase_timestamp) = 2024
  AND customer_unique_id IN (
      SELECT DISTINCT customer_unique_id 
      FROM customers c2
      INNER JOIN orders o2 ON c2.customer_id = o2.customer_id
      WHERE YEAR(o2.order_purchase_timestamp) = 2026
  );


