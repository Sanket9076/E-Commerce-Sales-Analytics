-- 71. ROW_NUMBER: Row number assigned to items in each order to sequence them
SELECT 
    order_id, 
    product_id, 
    price,
    ROW_NUMBER() OVER (PARTITION BY order_id ORDER BY price DESC) AS item_price_rank
FROM order_items
LIMIT 15;

-- 72. RANK: Rank categories by total products count
SELECT 
    product_category_name, 
    COUNT(*) AS prod_count,
    RANK() OVER (ORDER BY COUNT(*) DESC) AS category_rank
FROM products
GROUP BY product_category_name;

-- 73. DENSE_RANK: Dense rank sellers by revenue generated
SELECT 
    seller_id, 
    revenue,
    DENSE_RANK() OVER (ORDER BY revenue DESC) AS seller_revenue_rank
FROM (
    SELECT seller_id, SUM(price * quantity) AS revenue 
    FROM order_items 
    GROUP BY seller_id
) AS SellerRevenue
LIMIT 10;

-- 74. NTILE: Divide customers into 4 quartiles based on total purchase monetary value
SELECT 
    customer_unique_id,
    total_spend,
    NTILE(4) OVER (ORDER BY total_spend DESC) AS spend_quartile
FROM (
    SELECT c.customer_unique_id, SUM(oi.price * oi.quantity) AS total_spend
    FROM orders o
    INNER JOIN customers c ON o.customer_id = c.customer_id
    INNER JOIN order_items oi ON o.order_id = oi.order_id
    GROUP BY c.customer_unique_id
) AS CustMonetary
LIMIT 15;

-- 75. Running Total of daily sales revenue using SUM OVER
SELECT 
    order_date,
    daily_revenue,
    SUM(daily_revenue) OVER (ORDER BY order_date) AS running_total_revenue
FROM (
    SELECT DATE(order_purchase_timestamp) AS order_date, SUM(price * quantity) AS daily_revenue
    FROM orders o
    INNER JOIN order_items oi ON o.order_id = oi.order_id
    GROUP BY DATE(order_purchase_timestamp)
) AS DailyRevenue
LIMIT 15;

-- 76. LEAD: Find the purchase date of the next order for repeat customers
SELECT 
    customer_unique_id,
    order_id,
    order_purchase_timestamp AS current_order_date,
    LEAD(order_purchase_timestamp) OVER (PARTITION BY customer_unique_id ORDER BY order_purchase_timestamp) AS next_order_date
FROM orders o
INNER JOIN customers c ON o.customer_id = c.customer_id
LIMIT 20;

-- 77. LAG: Compute the interval (days) between consecutive purchases of repeat users
WITH ConsecutivePurchases AS (
    SELECT 
        c.customer_unique_id,
        o.order_purchase_timestamp AS current_date,
        LAG(o.order_purchase_timestamp) OVER (PARTITION BY customer_unique_id ORDER BY o.order_purchase_timestamp) AS prev_date
    FROM orders o
    INNER JOIN customers c ON o.customer_id = c.customer_id
)
SELECT 
    customer_unique_id, 
    current_date, 
    prev_date,
    DATEDIFF(current_date, prev_date) AS days_between_purchases
FROM ConsecutivePurchases
WHERE prev_date IS NOT NULL;

-- 78. Moving Average: 7-day moving average of daily orders placed
WITH DailyOrderCounts AS (
    SELECT DATE(order_purchase_timestamp) AS order_date, COUNT(*) AS order_count
    FROM orders
    GROUP BY DATE(order_purchase_timestamp)
)
SELECT 
    order_date,
    order_count,
    AVG(order_count) OVER (ORDER BY order_date ROWS BETWEEN 6 PRECEDING AND CURRENT ROW) AS 7_day_moving_avg
FROM DailyOrderCounts;

-- 79. ROW_NUMBER: Select only the most recent order for each customer profile
WITH CustomerOrderRanks AS (
    SELECT 
        c.customer_unique_id,
        o.order_id,
        o.order_purchase_timestamp,
        ROW_NUMBER() OVER (PARTITION BY c.customer_unique_id ORDER BY o.order_purchase_timestamp DESC) AS order_recency_rank
    FROM orders o
    INNER JOIN customers c ON o.customer_id = c.customer_id
)
SELECT customer_unique_id, order_id, order_purchase_timestamp 
FROM CustomerOrderRanks
WHERE order_recency_rank = 1
LIMIT 10;

-- 80. Running Total: running sum of products added to inventory by category
SELECT 
    product_category_name,
    product_id,
    product_base_price,
    SUM(product_base_price) OVER (PARTITION BY product_category_name ORDER BY product_id) AS cumulative_category_value
FROM products;

-- 81. PERCENT_RANK: Percentile rank of products by price
SELECT 
    product_id, 
    product_category_name, 
    product_base_price,
    PERCENT_RANK() OVER (ORDER BY product_base_price DESC) AS price_percent_rank
FROM products
LIMIT 10;

-- 82. FIRST_VALUE: Retrieve the first order ID placed by each unique user
SELECT DISTINCT 
    c.customer_unique_id,
    FIRST_VALUE(o.order_id) OVER (PARTITION BY c.customer_unique_id ORDER BY o.order_purchase_timestamp ASC) AS first_order_id,
    FIRST_VALUE(o.order_purchase_timestamp) OVER (PARTITION BY c.customer_unique_id ORDER BY o.order_purchase_timestamp ASC) AS first_purchase_date
FROM orders o
INNER JOIN customers c ON o.customer_id = c.customer_id
LIMIT 15;

-- 83. LAST_VALUE: Find the last review score left by each user (handling bounds)
SELECT DISTINCT 
    c.customer_unique_id,
    LAST_VALUE(r.review_score) OVER (
        PARTITION BY c.customer_unique_id 
        ORDER BY r.review_creation_date 
        ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING
    ) AS last_review_score
FROM reviews r
INNER JOIN orders o ON r.order_id = o.order_id
INNER JOIN customers c ON o.customer_id = c.customer_id
LIMIT 15;

-- 84. LAG: Check the price changes for consecutive order items within the same order
SELECT 
    order_id,
    product_id,
    price,
    LAG(price) OVER (PARTITION BY order_id ORDER BY order_item_id) AS previous_item_price,
    price - LAG(price) OVER (PARTITION BY order_id ORDER BY order_item_id) AS price_diff
FROM order_items
LIMIT 15;

-- 85. 30-Day Moving Average: 30-day moving average of daily revenue
WITH DailySalesRevenue AS (
    SELECT DATE(order_purchase_timestamp) AS order_date, SUM(price * quantity) AS daily_revenue
    FROM orders o
    INNER JOIN order_items oi ON o.order_id = oi.order_id
