-- 96. Create View: Customer Order Lifetime Summary View
CREATE OR REPLACE VIEW view_customer_lifetime_summary AS
SELECT 
    c.customer_unique_id,
    c.customer_city,
    c.customer_state,
    MIN(o.order_purchase_timestamp) AS first_order_date,
    MAX(o.order_purchase_timestamp) AS last_order_date,
    COUNT(DISTINCT o.order_id) AS total_orders,
    SUM(oi.price * oi.quantity) AS total_spend,
    SUM(oi.freight_value) AS total_freight_paid,
    AVG(r.review_score) AS average_given_rating
FROM customers c
INNER JOIN orders o ON c.customer_id = o.customer_id
INNER JOIN order_items oi ON o.order_id = oi.order_id
LEFT JOIN reviews r ON o.order_id = r.order_id
GROUP BY c.customer_unique_id, c.customer_city, c.customer_state;

