GROUP BY customer_state 
ORDER BY customer_count DESC;

-- 19. Find the total quantities sold for each product
SELECT product_id, SUM(quantity) AS total_qty_sold 
FROM order_items 
GROUP BY product_id 
ORDER BY total_qty_sold DESC;

-- 20. Count orders by their current status
SELECT order_status, COUNT(*) AS status_count 
FROM orders 
GROUP BY order_status;

-- 21. Get the average review score given by customers
SELECT AVG(review_score) AS average_review_score FROM reviews;

-- 22. Find the total revenue (excluding shipping) generated by the company
SELECT SUM(price * quantity) AS total_product_revenue FROM order_items;

-- 23. Find the total freight value paid across all orders
SELECT SUM(freight_value) AS total_freight_paid FROM order_items;

-- 24. List product categories and their total products count
SELECT product_category_name, COUNT(*) AS product_count 
