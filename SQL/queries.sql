-- 61. Categorize products into Price Brackets using CASE
SELECT 
    product_id, 
    product_base_price,
    CASE 
        WHEN product_base_price < 50 THEN 'Low Value'
        WHEN product_base_price BETWEEN 50 AND 200 THEN 'Medium Value'
        WHEN product_base_price BETWEEN 200 AND 800 THEN 'High Value'
        ELSE 'Premium Value'
    END AS price_tier
FROM products;

-- 62. Calculate refund percentage depending on return status
SELECT 
    return_id, 
    return_status,
    CASE 
        WHEN return_status = 'approved' THEN '100% Refunded'
        WHEN return_status = 'rejected' THEN '0% Refunded (Rejected)'
        ELSE 'Refund Processing (Pending)'
    END AS refund_state
FROM returns;

-- 63. Use COALESCE to handle null review comment titles
SELECT 
    review_id, 
    review_score, 
    COALESCE(review_comment_title, 'No Title Provided') AS clean_title 
FROM reviews 
LIMIT 10;

-- 64. Use CASE to label delivery status compared to estimated date
SELECT 
    order_id, 
    order_delivered_customer_date, 
    order_estimated_delivery_date,
    CASE 
        WHEN order_delivered_customer_date IS NULL THEN 'Not Delivered'
        WHEN order_delivered_customer_date <= order_estimated_delivery_date THEN 'On Time / Early'
        ELSE 'Delayed'
    END AS delivery_performance
FROM orders;

-- 65. UNION: Combine names of cities with customers and cities with sellers
SELECT DISTINCT customer_city AS city_name, 'Customer City' AS source_type FROM customers
UNION
SELECT DISTINCT seller_city AS city_name, 'Seller City' AS source_type FROM sellers
LIMIT 15;

-- 66. UNION ALL: Combine all SP state locations for review
SELECT customer_city AS SP_City FROM customers WHERE customer_state = 'SP'
UNION ALL
SELECT seller_city AS SP_City FROM sellers WHERE seller_state = 'SP'
LIMIT 15;

-- 67. COALESCE order approved timestamp, falling back to purchase date if payment approval was instant
SELECT 
    order_id, 
    order_purchase_timestamp, 
    COALESCE(order_approved_at, order_purchase_timestamp) AS final_approval_time 
FROM orders 
LIMIT 10;

-- 68. Classify review score sentiment using CASE
SELECT 
    review_id, 
    review_score,
    CASE 
        WHEN review_score >= 4 THEN 'Positive'
        WHEN review_score = 3 THEN 'Neutral'
        ELSE 'Negative'
    END AS customer_sentiment
FROM reviews;

-- 69. Calculate order status performance metrics conditionally
SELECT 
    COUNT(CASE WHEN order_status = 'delivered' THEN 1 END) AS delivered_count,
    COUNT(CASE WHEN order_status = 'canceled' THEN 1 END) AS canceled_count,
    COUNT(CASE WHEN order_status NOT IN ('delivered', 'canceled') THEN 1 END) AS ongoing_count,
    COUNT(*) AS total_orders
FROM orders;

-- 70. Group customers into Recency segments based on days since last purchase
WITH UserRecency AS (
    SELECT 
        c.customer_unique_id,
        DATEDIFF('2026-06-15 23:59:59', MAX(o.order_purchase_timestamp)) AS recency_days
    FROM orders o
    INNER JOIN customers c ON o.customer_id = c.customer_id
    GROUP BY c.customer_unique_id
)
SELECT 
    customer_unique_id, 
    recency_days,
    CASE 
        WHEN recency_days <= 30 THEN 'Active (0-30 days)'
        WHEN recency_days BETWEEN 31 AND 180 THEN 'Warm (31-180 days)'
        WHEN recency_days BETWEEN 181 AND 365 THEN 'Cold (181-365 days)'
        ELSE 'Inactive (1yr+)'
    END AS activity_status
FROM UserRecency;


