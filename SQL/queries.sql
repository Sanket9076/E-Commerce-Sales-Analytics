    (SELECT COUNT(*) FROM CohortRetained) AS retained_customers,
    ((SELECT COUNT(*) FROM CohortRetained) * 100.0 / (SELECT COUNT(*) FROM Cohort2024)) AS customer_retention_rate,
    (100.0 - ((SELECT COUNT(*) FROM CohortRetained) * 100.0 / (SELECT COUNT(*) FROM Cohort2024))) AS customer_churn_rate;

