-- 1. Retrieve all columns from the categories table
SELECT * FROM categories;

-- 2. List the first 10 customers sorted by city alphabetically
SELECT * FROM customers 
ORDER BY customer_city ASC 
LIMIT 10;

-- 3. Retrieve unique states where customers are located
SELECT DISTINCT customer_state FROM customers;

-- 4. Find all products belonging to the 'electronics' category
SELECT * FROM products 
WHERE product_category_name = 'electronics';

-- 5. List orders with 'canceled' status
SELECT * FROM orders 
WHERE order_status = 'canceled';

-- 6. Find products with a base price greater than $500
SELECT * FROM products 
WHERE product_base_price > 500.00;

-- 7. Retrieve sellers located in the state of 'SP' (São Paulo)
SELECT * FROM sellers 
WHERE seller_state = 'SP';

-- 8. Find orders placed between January 1, 2025, and January 31, 2025
SELECT * FROM orders 
WHERE order_purchase_timestamp BETWEEN '2025-01-01 00:00:00' AND '2025-01-31 23:59:59';

-- 9. List products that have between 3 and 5 photos
SELECT * FROM products 
WHERE product_photos_qty BETWEEN 3 AND 5;

-- 10. Find customers whose city name starts with 'Belo'
SELECT * FROM customers 
WHERE customer_city LIKE 'Belo%';

-- 11. Find reviews where the score is either 1 or 2 (low satisfaction)
SELECT * FROM reviews 
WHERE review_score IN (1, 2);

-- 12. Find orders where the carrier delivery date is NULL (shipped but not yet received by carrier, or processing)
SELECT * FROM orders 
WHERE order_delivered_carrier_date IS NULL;

-- 13. Find reviews that have a comment title
SELECT * FROM reviews 
WHERE review_comment_title IS NOT NULL AND review_comment_title <> '';

-- 14. List products sorted by weight descending, showing the top 5 heaviest
SELECT * FROM products 
ORDER BY product_weight_g DESC 
LIMIT 5;

-- 15. Retrieve return requests that are currently 'pending'
SELECT * FROM returns 
WHERE return_status = 'pending';


-- ====================================================================
-- SECTION 2: Aggregations, Grouping, and Filtering on Aggregations (Queries 16-30)
-- ====================================================================

-- 16. Count the total number of orders in the database
SELECT COUNT(*) AS total_orders FROM orders;

-- 17. Find the minimum, maximum, and average product base price
SELECT 
    MIN(product_base_price) AS min_price, 
    MAX(product_base_price) AS max_price, 
    AVG(product_base_price) AS avg_price 
FROM products;

-- 18. Count the number of customers in each state
SELECT customer_state, COUNT(*) AS customer_count 
