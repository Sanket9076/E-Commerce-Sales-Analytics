-- 90. Pareto 80/20 spend rule validation: Find the customer base generating 80% revenue
WITH CustomerSales AS (
    SELECT c.customer_unique_id, SUM(oi.price * oi.quantity) AS spend
    FROM orders o
    INNER JOIN customers c ON o.customer_id = c.customer_id
    INNER JOIN order_items oi ON o.order_id = oi.order_id
    GROUP BY c.customer_unique_id
),
RunningSales AS (
    SELECT 
        customer_unique_id,
        spend,
        SUM(spend) OVER (ORDER BY spend DESC) AS cumulative_spend,
        (SELECT SUM(price * quantity) FROM order_items) AS total_revenue,
        ROW_NUMBER() OVER (ORDER BY spend DESC) AS row_num,
        (SELECT COUNT(DISTINCT customer_unique_id) FROM customers) AS total_customers
    FROM CustomerSales
)
SELECT 
    row_num AS customer_count,
    (row_num * 100.0 / total_customers) AS customer_percentage,
    spend AS customer_spend,
    (cumulative_spend * 100.0 / total_revenue) AS cumulative_revenue_percentage
FROM RunningSales
WHERE (cumulative_spend * 100.0 / total_revenue) <= 80.05
ORDER BY row_num DESC
LIMIT 1;

-- 91. ABC Product Analysis: Group products into classes based on revenue share
WITH ProductRevenue AS (
    SELECT product_id, SUM(price * quantity) AS revenue
    FROM order_items
    GROUP BY product_id
),
ProductCumulative AS (
    SELECT 
        product_id,
        revenue,
        SUM(revenue) OVER (ORDER BY revenue DESC) AS cum_revenue,
        (SELECT SUM(price * quantity) FROM order_items) AS total_revenue
    FROM ProductRevenue
),
ABCClassification AS (
    SELECT 
        product_id,
        revenue,
        (cum_revenue / total_revenue) AS cum_share,
        CASE 
            WHEN (cum_revenue / total_revenue) <= 0.70 THEN 'A'
            WHEN (cum_revenue / total_revenue) <= 0.90 THEN 'B'
            ELSE 'C'
        END AS abc_class
    FROM ProductCumulative
)
SELECT 
    abc_class,
    COUNT(product_id) AS product_count,
    (COUNT(product_id) * 100.0 / (SELECT COUNT(*) FROM products)) AS product_pct,
    SUM(revenue) AS total_class_revenue,
    (SUM(revenue) * 100.0 / (SELECT SUM(price * quantity) FROM order_items)) AS revenue_pct
FROM ABCClassification
GROUP BY abc_class
ORDER BY abc_class;

-- 92. RFM Quintiles calculation using Window NTILE
WITH CustomerRFM AS (
    SELECT 
        c.customer_unique_id,
        DATEDIFF('2026-06-15 23:59:59', MAX(o.order_purchase_timestamp)) AS recency,
        COUNT(o.order_id) AS frequency,
        SUM(oi.price * oi.quantity) AS monetary
    FROM orders o
    INNER JOIN customers c ON o.customer_id = c.customer_id
    INNER JOIN order_items oi ON o.order_id = oi.order_id
    GROUP BY c.customer_unique_id
),
RFM_Scores AS (
    SELECT 
        customer_unique_id,
        recency, frequency, monetary,
        NTILE(5) OVER (ORDER BY recency ASC) AS r_score_inv, -- recency lower is better
        NTILE(5) OVER (ORDER BY frequency DESC) AS f_score,
        NTILE(5) OVER (ORDER BY monetary DESC) AS m_score
    FROM CustomerRFM
)
SELECT 
    customer_unique_id,
    recency, frequency, monetary,
    (6 - r_score_inv) AS r_score, -- Invert score so low recency days = 5
    f_score, m_score
FROM RFM_Scores
LIMIT 15;

-- 93. Month-over-Month Revenue Growth Rate
WITH MonthlySales AS (
    SELECT 
        DATE_FORMAT(order_purchase_timestamp, '%Y-%m') AS sale_month,
        SUM(price * quantity) AS revenue
    FROM orders o
    INNER JOIN order_items oi ON o.order_id = oi.order_id
    GROUP BY DATE_FORMAT(order_purchase_timestamp, '%Y-%m')
),
MonthlyComparisons AS (
    SELECT 
        sale_month,
        revenue,
        LAG(revenue) OVER (ORDER BY sale_month) AS prev_month_revenue
    FROM MonthlySales
)
SELECT 
    sale_month,
    revenue AS current_month_revenue,
    prev_month_revenue,
    ((revenue - prev_month_revenue) * 100.0 / prev_month_revenue) AS mom_growth_rate_pct
FROM MonthlyComparisons
WHERE prev_month_revenue IS NOT NULL
ORDER BY sale_month;

-- 94. Product Category Return Rates (defective returns vs total items sold)
SELECT 
    p.product_category_name,
    COUNT(oi.order_item_id) AS items_sold,
    COUNT(r.return_id) AS return_requests,
    (COUNT(r.return_id) * 100.0 / COUNT(oi.order_item_id)) AS return_rate_pct,
    COUNT(CASE WHEN r.return_reason = 'defective' THEN 1 END) AS defective_returns_count
FROM order_items oi
INNER JOIN products p ON oi.product_id = p.product_id
LEFT JOIN returns r ON oi.order_id = r.order_id AND oi.product_id = r.product_id
GROUP BY p.product_category_name
ORDER BY return_rate_pct DESC;

-- 95. Net Promoter Score (NPS) / Satisfaction Index based on Reviews (CSAT equivalent)
